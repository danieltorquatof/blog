"""Quarto post-render script: SEO touches Quarto does not provide out of the box.

- Canonical URLs without "index.html" (rel=canonical, og:url and sitemap.xml)
- Per-page social preview cards (generated by utils/og_images.py) in og:image / twitter:image
- JSON-LD structured data (WebSite, Person, ProfilePage, CollectionPage, BlogPosting/Article,
  BreadcrumbList)
- UUID short links: a page with `uuid: <id>` in its front matter also answers at
  /<section>/<id>/, a redirect page pointing to its keyword URL (/<section>/<slug>/)
- Removes the empty files Quarto still writes for draft pages (draft-mode: gone)

Safe to run repeatedly (quarto preview re-runs it after each incremental render).
"""

import html
import json
import os
import re
import shutil
from datetime import date, datetime
from html.parser import HTMLParser
from pathlib import Path
from typing import Any

from site_pages import PROJECT_DIR, Page, discoverPages, loadSiteConfig

OUTPUT_DIR: Path = PROJECT_DIR / os.environ.get("QUARTO_PROJECT_OUTPUT_DIR", "_site")

JSON_LD_ID: str = "seo-json-ld"

ARTICLE_TYPES: dict[str, str] = {
    "posts": "BlogPosting",
    "articles": "Article",
    "projects": "CreativeWork",
    "achievements": "CreativeWork",
}

REDIRECT_TEMPLATE: str = """<!DOCTYPE html>
<html lang="{lang}">
<head>
  <meta charset="utf-8">
  <title>{title}</title>
  <link rel="canonical" href="{url}">
  <meta http-equiv="refresh" content="0; url={target}">
{social}
  <script>window.location.replace("{target}" + window.location.search + window.location.hash);</script>
</head>
<body>
  <p>Redirecting to <a href="{target}">{title}</a>…</p>
</body>
</html>
"""


class HeadMetaParser(HTMLParser):
    """Collects <meta> tags and the <title> of a rendered page."""

    def __init__(self) -> None:
        super().__init__()
        self.meta: dict[str, str] = {}
        self.socialTags: list[str] = []
        self.title: str = ""
        self._inTitle: bool = False

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        attributes: dict[str, str] = {key: value or "" for key, value in attrs}

        if tag == "title":
            self._inTitle = True
        elif tag == "meta":
            key: str = attributes.get("property") or attributes.get("name") or ""

            if key and "content" in attributes:
                self.meta.setdefault(key, attributes["content"])

                if key.startswith(("og:", "twitter:")) or key == "description":
                    self.socialTags.append(self.get_starttag_text() or "")

    def handle_endtag(self, tag: str) -> None:
        if tag == "title":
            self._inTitle = False

    def handle_data(self, data: str) -> None:
        if self._inTitle:
            self.title += data


def parseHead(document: str) -> HeadMetaParser:
    parser = HeadMetaParser()
    parser.feed(document.split("</head>", 1)[0])

    return parser


def isoDate(value: Any) -> str | None:
    if isinstance(value, (date, datetime)):
        return value.isoformat()

    return str(value) if value else None


def absoluteUrl(siteUrl: str, path: str) -> str:
    return siteUrl.rstrip("/") + "/" + path.lstrip("/")


def jsonLdScript(data: dict[str, Any]) -> str:
    payload: str = json.dumps(data, ensure_ascii=False, indent=2).replace("</", "<\\/")

    return f'<script type="application/ld+json" id="{JSON_LD_ID}">\n{payload}\n</script>'


class SeoContext:
    def __init__(self) -> None:
        config: dict[str, Any] = loadSiteConfig()

        self.website: dict[str, Any] = config["website"]
        self.siteUrl: str = self.website["site-url"]
        self.lang: str = config.get("lang", "en")
        self.pages: list[Page] = [page for page in discoverPages() if not page.isDraft]

        resume: Page | None = next(
            (page for page in self.pages if page.relativeSource.as_posix() == "aboutMe/resume.qmd"),
            None,
        )

        sameAs: list[str] = [
            tool["href"]
            for tool in self.website.get("navbar", {}).get("tools", [])
            if str(tool.get("href", "")).startswith("http")
        ]

        self.person: dict[str, Any] = {
            "@type": "Person",
            "@id": absoluteUrl(self.siteUrl, "#person"),
            "name": self.website["title"],
            "url": absoluteUrl(self.siteUrl, resume.urlPath if resume else ""),
            "sameAs": sameAs,
        }

        if resume and resume.meta.get("description"):
            self.person["jobTitle"] = resume.meta["description"]

        self.webSite: dict[str, Any] = {
            "@type": "WebSite",
            "@id": absoluteUrl(self.siteUrl, "#website"),
            "name": self.website["title"],
            "alternateName": self.website.get("navbar", {}).get("title"),
            "description": self.website.get("description"),
            "url": self.siteUrl,
            "inLanguage": self.lang,
            "author": {"@id": self.person["@id"]},
            "publisher": {"@id": self.person["@id"]},
        }

    def pageUrl(self, page: Page) -> str:
        return absoluteUrl(self.siteUrl, page.urlPath)

    def sectionPage(self, section: str) -> Page | None:
        return next(
            (page for page in self.pages if page.relativeSource.as_posix() == f"{section}/index.qmd"),
            None,
        )

    def breadcrumbs(self, page: Page, title: str) -> dict[str, Any]:
        items: list[dict[str, Any]] = [{"name": self.website["title"], "item": self.siteUrl}]

        section: str = page.relativeSource.parts[0]
        sectionPage: Page | None = self.sectionPage(section)

        if sectionPage:
            items.append({"name": sectionPage.meta.get("title", section), "item": self.pageUrl(sectionPage)})

        items.append({"name": title, "item": self.pageUrl(page)})

        return {
            "@type": "BreadcrumbList",
            "itemListElement": [
                {"@type": "ListItem", "position": position, **item}
                for position, item in enumerate(items, start=1)
            ],
        }

    def structuredData(self, page: Page, head: HeadMetaParser) -> dict[str, Any] | None:
        path: str = page.relativeSource.as_posix()
        parts: tuple[str, ...] = page.relativeSource.parts
        url: str = self.pageUrl(page)
        title: str = str(page.meta.get("title", self.website["title"]))
        description: str | None = page.meta.get("description") or head.meta.get("description")
        image: str | None = head.meta.get("og:image")

        if path == "404.qmd":
            return None

        graph: list[dict[str, Any]] = [self.webSite, self.person]

        if path == "index.qmd":
            graph.append(
                {
                    "@type": "WebPage",
                    "@id": url,
                    "url": url,
                    "name": page.meta.get("pagetitle", title),
                    "description": description,
                    "isPartOf": {"@id": self.webSite["@id"]},
                    "about": {"@id": self.person["@id"]},
                    "inLanguage": self.lang,
                }
            )
        elif path == "aboutMe/resume.qmd":
            graph.append(
                {
                    "@type": "ProfilePage",
                    "@id": url,
                    "url": url,
                    "name": title,
                    "description": description,
                    "isPartOf": {"@id": self.webSite["@id"]},
                    "mainEntity": {"@id": self.person["@id"]},
                    "inLanguage": self.lang,
                }
            )
        elif len(parts) == 2 and parts[1] == "index.qmd" and parts[0] in ARTICLE_TYPES:
            graph.append(
                {
                    "@type": "CollectionPage",
                    "@id": url,
                    "url": url,
                    "name": title,
                    "description": description,
                    "isPartOf": {"@id": self.webSite["@id"]},
                    "inLanguage": self.lang,
                }
            )
        elif parts[0] in ARTICLE_TYPES:
            published: str | None = isoDate(page.meta.get("date"))

            article: dict[str, Any] = {
                "@type": ARTICLE_TYPES[parts[0]],
                "@id": url,
                "url": url,
                "mainEntityOfPage": url,
                "headline": title,
                "alternativeHeadline": page.meta.get("subtitle"),
                "description": description,
                "image": image,
                "datePublished": published,
                "dateModified": isoDate(page.meta.get("date-modified")) or published,
                "keywords": [str(category) for category in page.meta.get("categories") or []],
                "author": {"@id": self.person["@id"]},
                "publisher": {"@id": self.person["@id"]},
                "isPartOf": {"@id": self.webSite["@id"]},
                "inLanguage": self.lang,
            }

            graph.extend([article, self.breadcrumbs(page, title)])
        else:
            graph.append(
                {
                    "@type": "WebPage",
                    "@id": url,
                    "url": url,
                    "name": title,
                    "description": description,
                    "isPartOf": {"@id": self.webSite["@id"]},
                    "inLanguage": self.lang,
                }
            )

        return {
            "@context": "https://schema.org",
            "@graph": [{key: value for key, value in node.items() if value not in (None, "", [])} for node in graph],
        }


def cleanUrl(url: str) -> str:
    return re.sub(r"(^|/)index\.html$", r"\1", url)


def replaceMetaContent(document: str, attribute: str, key: str, value: str) -> str:
    return re.sub(
        rf'(<meta {attribute}="{re.escape(key)}" content=")[^"]*(")',
        lambda match: f"{match.group(1)}{html.escape(value)}{match.group(2)}",
        document,
    )


def addMetaAfter(document: str, attribute: str, anchorKey: str, key: str, value: str) -> str:
    if f'<meta {attribute}="{key}"' in document:
        return document

    return re.sub(
        rf'<meta {attribute}="{re.escape(anchorKey)}" content="[^"]*">',
        lambda match: f'{match.group(0)}\n<meta {attribute}="{key}" content="{html.escape(value)}">',
        document,
        count=1,
    )


def publishSocialCard(context: SeoContext, page: Page, document: str) -> str:
    card: Path = PROJECT_DIR / page.socialCard

    if not page.usesGeneratedCard or not card.exists():
        return document

    cardOutput: Path = OUTPUT_DIR / page.socialCard
    cardOutput.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(card, cardOutput)

    cardUrl: str = absoluteUrl(context.siteUrl, page.socialCard.as_posix())

    document = replaceMetaContent(document, "property", "og:image", cardUrl)
    document = replaceMetaContent(document, "name", "twitter:image", cardUrl)

    # The site-wide image-alt describes the default card, not this one
    imageAlt: str = html.unescape(parseHead(document).meta.get("og:title", context.website["title"]))
    document = replaceMetaContent(document, "property", "og:image:alt", imageAlt)
    document = replaceMetaContent(document, "name", "twitter:image:alt", imageAlt)

    return document


def updateNotFoundPage(output: Path, document: str) -> bool:
    """GitHub Pages serves 404.html for any missing URL: no canonical, never indexed."""
    updated: str = re.sub(r'<link rel="canonical" href="[^"]*"\s*/?>\n?', "", document)

    if '<meta name="robots"' not in updated:
        updated = updated.replace("</head>", '<meta name="robots" content="noindex">\n</head>', 1)

    if updated != document:
        output.write_text(updated, encoding="utf-8")

    return True


def updatePage(context: SeoContext, page: Page) -> bool:
    output: Path = OUTPUT_DIR / page.outputPath

    if not output.exists():
        return False

    document: str = output.read_text(encoding="utf-8")
    original: str = document
    url: str = context.pageUrl(page)

    if page.relativeSource.as_posix() == "404.qmd":
        return updateNotFoundPage(output, document)

    document = re.sub(
        r'<link rel="canonical" href="[^"]*"\s*/?>',
        lambda _: f'<link rel="canonical" href="{html.escape(url)}">',
        document,
        count=1,
    )

    document = publishSocialCard(context, page, document)

    imageAlt: str = html.unescape(parseHead(document).meta.get("og:title", context.website["title"]))
    document = addMetaAfter(document, "property", "og:image", "og:image:alt", imageAlt)
    document = addMetaAfter(document, "name", "twitter:image", "twitter:image:alt", imageAlt)

    head: HeadMetaParser = parseHead(document)

    if "og:title" in head.meta and "og:url" not in head.meta:
        document = document.replace(
            '<meta property="og:title"',
            f'<meta property="og:url" content="{html.escape(url)}">\n<meta property="og:title"',
            1,
        )

    document = re.sub(
        rf'\n?<script type="application/ld\+json" id="{JSON_LD_ID}">.*?</script>',
        "",
        document,
        flags=re.DOTALL,
    )

    data: dict[str, Any] | None = context.structuredData(page, head)

    if data:
        document = document.replace("</head>", f"{jsonLdScript(data)}\n</head>", 1)

    if document != original:
        output.write_text(document, encoding="utf-8")

    return True


def writeShortLink(context: SeoContext, page: Page) -> str | None:
    uuid: str | None = page.meta.get("uuid")

    if not uuid or page.relativeSource.name != "index.qmd":
        return None

    target: Path = OUTPUT_DIR / page.outputPath
    shortLink: Path = target.parent.parent / str(uuid) / "index.html"

    if not target.exists():
        return None

    if shortLink.parent == target.parent:
        return None

    url: str = context.pageUrl(page)
    head: HeadMetaParser = parseHead(target.read_text(encoding="utf-8"))

    social: str = "\n".join(f"  {tag}" for tag in head.socialTags)

    shortLink.parent.mkdir(parents=True, exist_ok=True)
    shortLink.write_text(
        REDIRECT_TEMPLATE.format(
            lang=context.lang,
            title=html.escape(head.title.strip() or str(page.meta.get("title", ""))),
            url=html.escape(url),
            # Relative, so the short link also works on localhost / previews
            target=html.escape(f"../{target.parent.name}/"),
            social=social,
        ),
        encoding="utf-8",
    )

    return shortLink.relative_to(OUTPUT_DIR).as_posix()


def updateSitemap(context: SeoContext) -> None:
    sitemap: Path = OUTPUT_DIR / "sitemap.xml"

    if not sitemap.exists():
        return

    content: str = sitemap.read_text(encoding="utf-8")
    updated: str = re.sub(r"<loc>([^<]*)</loc>", lambda match: f"<loc>{cleanUrl(match.group(1))}</loc>", content)

    if updated != content:
        sitemap.write_text(updated, encoding="utf-8")


def removeDraftOutputs() -> int:
    removed: int = 0

    for page in discoverPages():
        output: Path = OUTPUT_DIR / page.outputPath

        if page.isDraft and output.exists():
            output.unlink()
            removed += 1

            if output.parent != OUTPUT_DIR and not any(output.parent.iterdir()):
                output.parent.rmdir()

    return removed


def main() -> None:
    context = SeoContext()

    removedDrafts: int = removeDraftOutputs()

    updated: int = sum(updatePage(context, page) for page in context.pages)
    shortLinks: list[str] = [link for page in context.pages if (link := writeShortLink(context, page))]

    updateSitemap(context)

    print(
        f"seo_postrender: {updated} page(s) processed, {len(shortLinks)} UUID short link(s) written, "
        f"{removedDrafts} draft output(s) removed"
    )


if __name__ == "__main__":
    main()
